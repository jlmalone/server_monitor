#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="${HOME}/.local/bin"
GROK_BIN_DIR="${HOME}/.grok/bin"
CONFIG_DIR="${HOME}/.config/agent-dangerously"
MANIFEST="${CONFIG_DIR}/manifest.env"
CURSOR_DANGEROUSLY="${ROOT}/cursor-file-dangerously"

mkdir -p "$CONFIG_DIR" "$BIN_DIR" "$GROK_BIN_DIR"

resolve_link_target() {
  local path="$1"
  local current="$path"
  local dir=""

  if [[ ! -e "$current" ]]; then
    return 1
  fi

  while [[ -L "$current" ]]; do
    dir="$(cd "$(dirname "$current")" && pwd)"
    current="$(readlink "$current")"
    [[ "$current" != /* ]] && current="${dir}/${current}"
  done

  if [[ -x "$current" ]]; then
    printf '%s\n' "$current"
    return 0
  fi
  return 1
}

preserve_real_binary() {
  local name="$1"
  local current="$2"
  local real_dir="$3"
  local real_path="${real_dir}/${name}.real"
  local recorded=""

  if [[ -L "$current" ]]; then
    recorded="$(readlink "$current")"
    if [[ "$recorded" == *-dangerously* || "$recorded" == *cursor-file-dangerously* ]]; then
      if [[ -L "$real_path" ]]; then
        return 0
      fi
      return 1
    fi
    ln -sfn "$recorded" "$real_path"
    return 0
  fi

  if [[ -x "$current" && ! -e "$real_path" ]]; then
    ln -sfn "$current" "$real_path"
  fi
}

install_script_link() {
  local source="$1"
  local dest="$2"
  ln -sfn "$source" "$dest"
  chmod +x "$source"
}

: >"$MANIFEST"
printf '# Generated by install-agent-dangerously-shims.sh\n' >>"$MANIFEST"

if [[ -e "${BIN_DIR}/codex" ]]; then
  preserve_real_binary codex "${BIN_DIR}/codex" "$BIN_DIR" || true
fi
printf 'CODEX_REAL=%q\n' "$(resolve_link_target "${BIN_DIR}/codex.real" 2>/dev/null || printf '%s' "${HOME}/.codex/packages/standalone/current/bin/codex")" >>"$MANIFEST"
install_script_link "${ROOT}/codex-dangerously" "${BIN_DIR}/codex_dangerously"
install_script_link "${ROOT}/codex-dangerously" "${BIN_DIR}/codex"

if [[ -e "${BIN_DIR}/claude" ]]; then
  preserve_real_binary claude "${BIN_DIR}/claude" "$BIN_DIR" || true
fi
CLAUDE_REAL_CANDIDATE="$(resolve_link_target "${BIN_DIR}/claude.real" 2>/dev/null || true)"
if [[ -z "$CLAUDE_REAL_CANDIDATE" ]]; then
  CLAUDE_VERSION="$(ls -1 "${HOME}/.local/share/claude/versions" 2>/dev/null | sort | tail -1 || true)"
  if [[ -n "$CLAUDE_VERSION" ]]; then
    CLAUDE_REAL_CANDIDATE="${HOME}/.local/share/claude/versions/${CLAUDE_VERSION}"
  fi
fi
printf 'CLAUDE_REAL=%q\n' "$CLAUDE_REAL_CANDIDATE" >>"$MANIFEST"
install_script_link "${ROOT}/claude-dangerously" "${BIN_DIR}/claude_dangerously"
install_script_link "${ROOT}/claude-dangerously" "${BIN_DIR}/claude"

if [[ -e "${GROK_BIN_DIR}/grok" ]]; then
  preserve_real_binary grok "${GROK_BIN_DIR}/grok" "$GROK_BIN_DIR" || true
fi
printf 'GROK_REAL=%q\n' "$(resolve_link_target "${GROK_BIN_DIR}/grok.real" 2>/dev/null || readlink "${GROK_BIN_DIR}/grok" 2>/dev/null || printf '%s' "${HOME}/.grok/downloads/grok-1.0.30-macos-aarch64")" >>"$MANIFEST"
install_script_link "${ROOT}/grok-dangerously" "${GROK_BIN_DIR}/grok_dangerously"
install_script_link "${ROOT}/grok-dangerously" "${GROK_BIN_DIR}/grok"

install_script_link "$CURSOR_DANGEROUSLY" "${BIN_DIR}/cursor_dangerously"
ln -sfn "$CURSOR_DANGEROUSLY" "${BIN_DIR}/cursor-agent"

chmod +x \
  "${ROOT}/agent-dangerously-common.sh" \
  "${ROOT}/codex-dangerously" \
  "${ROOT}/claude-dangerously" \
  "${ROOT}/grok-dangerously" \
  "$CURSOR_DANGEROUSLY"

cat <<EOF
Installed agent dangerously shims.

Canonical commands now route through dangerously wrappers:
  ${BIN_DIR}/codex           -> codex-dangerously
  ${BIN_DIR}/codex_dangerously
  ${BIN_DIR}/claude          -> claude-dangerously
  ${BIN_DIR}/claude_dangerously
  ${GROK_BIN_DIR}/grok       -> grok-dangerously
  ${GROK_BIN_DIR}/grok_dangerously
  ${BIN_DIR}/cursor-agent    -> cursor-file-dangerously
  ${BIN_DIR}/cursor_dangerously

Manifest: ${MANIFEST}
EOF
